"""Create a SYNTHETIC flights.csv for testing the setup.

The data is made up and must NOT be used as real-world evidence.

    python src/make_sample_data.py                    # 11-row sample from the guide
    python src/make_sample_data.py --rows 20000       # larger random sample (fills every summary)
    python src/make_sample_data.py --output data/raw/sample_flights.csv
"""
from __future__ import annotations

import argparse
import calendar
import csv
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "data" / "raw" / "flights.csv"

COLUMNS = [
    "Year", "Month", "DayofMonth", "DayOfWeek", "Reporting_Airline",
    "Origin", "Dest", "CRSDepTime", "DepDelay", "ArrDelay", "Cancelled",
    "Diverted", "CarrierDelay", "WeatherDelay", "NASDelay",
    "SecurityDelay", "LateAircraftDelay",
]

GUIDE_ROWS = [
    [2024, 1, 1, 1, "AA", "JFK", "ORD", 800, 10, 20, 0, 0, 10, 0, 10, 0, 0],
    [2024, 1, 1, 1, "DL", "ATL", "JFK", 930, 25, 35, 0, 0, 20, 0, 15, 0, 0],
    [2024, 1, 2, 2, "UA", "ORD", "LAX", 1410, -3, 2, 0, 0, 0, 0, 0, 0, 0],
    [2024, 1, 2, 2, "AA", "JFK", "ATL", 1730, 40, 55, 0, 0, 25, 0, 10, 0, 20],
    [2024, 2, 4, 7, "DL", "ATL", "ORD", 2200, 0, -5, 0, 0, 0, 0, 0, 0, 0],
    [2024, 2, 5, 1, "UA", "LAX", "JFK", 600, 70, 80, 0, 0, 20, 10, 20, 0, 30],
    [2024, 2, 6, 2, "AA", "ORD", "JFK", 1200, 5, 18, 0, 0, 0, 0, 13, 0, 0],
    [2024, 2, 7, 3, "DL", "JFK", "ATL", 1500, 0, 0, 0, 0, 0, 0, 0, 0, 0],
    [2024, 3, 8, 5, "UA", "ATL", "LAX", 1100, 15, 25, 0, 0, 0, 0, 15, 0, 10],
    [2024, 3, 9, 6, "AA", "LAX", "ORD", 1900, 0, None, 1, 0, None, None, None, None, None],
    [2024, 3, 10, 7, "DL", "ORD", "ATL", 700, 5, None, 0, 1, None, None, None, None, None],
]

AIRLINES = {"AA": 1.0, "DL": 0.7, "UA": 1.1, "WN": 1.2, "B6": 1.4, "AS": 0.8}
AIRPORTS = {"ATL": 0.9, "ORD": 1.3, "DFW": 1.1, "DEN": 1.0, "LAX": 1.0,
            "JFK": 1.3, "SFO": 1.2, "SEA": 0.8, "MCO": 1.1, "EWR": 1.4}


def random_rows(count: int, year: int, seed: int) -> list[list]:
    rng = random.Random(seed)
    codes = list(AIRPORTS)
    rows = []
    for _ in range(count):
        month = rng.randint(1, 12)
        day = rng.randint(1, calendar.monthrange(year, month)[1])
        weekday = calendar.weekday(year, month, day) + 1  # Monday=1 like BTS
        airline = rng.choice(list(AIRLINES))
        origin, dest = rng.sample(codes, 2)
        hour = rng.choices(range(5, 24), weights=[2, 6, 7, 7, 6, 6, 6, 6, 6, 6, 6, 6, 6, 6, 5, 4, 3, 2, 1])[0]
        dep_time = hour * 100 + rng.choice([0, 15, 30, 45])
        # Later hours, summer/December months, and congested airports delay more.
        factor = (AIRLINES[airline] * AIRPORTS[origin] * AIRPORTS[dest]
                  * (1 + hour / 24) * (1.3 if month in (6, 7, 12) else 1.0))
        cancelled = 1 if rng.random() < 0.015 * factor else 0
        diverted = 1 if not cancelled and rng.random() < 0.003 else 0
        dep_delay = None if cancelled else round(rng.expovariate(1 / (9 * factor)) - 6)
        if cancelled or diverted:
            arr_delay = None
        else:
            arr_delay = round(dep_delay + rng.gauss(-4, 8))
        causes = [None] * 5
        if arr_delay is not None and arr_delay >= 15:
            weights = [rng.random() * w for w in (3, 0.6, 2.5, 0.05, 3.5)]
            total = sum(weights)
            causes = [round(arr_delay * w / total) for w in weights]
        rows.append([year, month, day, weekday, airline, origin, dest, dep_time,
                     dep_delay, arr_delay, cancelled, diverted, *causes])
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description="Create a synthetic flights.csv")
    parser.add_argument("--rows", type=int, default=0,
                        help="Generate N random rows instead of the 11-row guide sample")
    parser.add_argument("--year", type=int, default=2024)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--output", default=str(DEFAULT_OUT))
    args = parser.parse_args()

    out = Path(args.output).resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    rows = random_rows(args.rows, args.year, args.seed) if args.rows > 0 else GUIDE_ROWS

    with out.open("w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file)
        writer.writerow(COLUMNS)
        writer.writerows(rows)

    if out == DEFAULT_OUT:
        # The dashboard reads this note, so synthetic results are clearly labelled.
        (out.parent / "DATA_SOURCE.txt").write_text(
            "Source: SYNTHETIC sample generated by src/make_sample_data.py "
            "(not real-world data)\n"
            f"Rows: {len(rows):,}\n",
            encoding="utf-8",
        )

    print(f"Wrote {len(rows):,} synthetic rows to {out}")
    print("SYNTHETIC DATA - for setup testing only. Use official BTS data for analysis.")


if __name__ == "__main__":
    main()
